import Foundation

/// ロン点 → 代表的な符・翻の目安（子＝親以外の手を基準）。
/// 計算機モードで「最低◯◯点（目安：◯符◯翻）」を示すために使う。
/// 厳密な点数計算ではなく、実戦でよく使う代表値の対応。
enum HanFuReference {
    /// 子（非親）ロンの代表的な符・翻表記
    private static let nonDealer: [Int: String] = [
        1000:  "30符1翻",
        1300:  "40符1翻",
        1600:  "50符1翻",
        2000:  "30符2翻",
        2600:  "40符2翻",
        3200:  "50符2翻",
        3900:  "30符3翻",
        5200:  "40符3翻",
        6400:  "50符3翻",
        7700:  "30符4翻",
        8000:  "満貫",
        12000: "跳満",
        16000: "倍満",
        24000: "三倍満",
        32000: "役満"
    ]

    /// ロン点の符翻目安を返す（例: 2600 → "40符2翻"）。
    static func hint(forRon points: Int) -> String? {
        nonDealer[points]
    }
}
